export function calcularOrdenes(valores) {
  const distancias = ORDENES.map(() => 0)
  PREGUNTAS.forEach((pregunta, i) => {
    const valor = valores[i]
    const fila = TRAIT_DATA[pregunta.trait]
    for (let j = 0; j < ORDENES.length; j += 1) {
      distancias[j] += (fila[j] - valor) ** 2
    }
  })

  distancias[9] *= 1.3

  return distancias
    .map((distancia, i) => ({
      orden: ORDENES[i],
      indice: i,
      distancia,

      porcentaje: Math.max(0, Math.min(100, Math.floor((120000 - distancia) / 1200))),
    }))
    .sort((a, b) => a.distancia - b.distancia)
}
